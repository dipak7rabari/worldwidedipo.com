const MAX_REFERRER_LENGTH = 120;
const MAX_VISITOR_HASH_LENGTH = 128;

const DEVICE_TYPES = new Set([
  'mobile',
  'tablet',
  'desktop',
  'unknown',
]);

export function normalizeDeviceType(
  value
) {
  if (
    typeof value !== 'string'
  ) {
    return 'unknown';
  }

  const normalized =
    value.trim().toLowerCase();

  return DEVICE_TYPES.has(
    normalized
  )
    ? normalized
    : 'unknown';
}

export function normalizeReferrer(
  value
) {
  if (
    typeof value !== 'string' ||
    !value.trim()
  ) {
    return null;
  }

  try {
    const url = new URL(
      value.trim()
    );

    if (
      url.protocol !== 'https:' &&
      url.protocol !== 'http:'
    ) {
      return null;
    }

    const hostname =
      url.hostname
        .toLowerCase()
        .replace(
          /^www\./,
          ''
        );

    if (
      hostname.length === 0 ||
      hostname.length >
        MAX_REFERRER_LENGTH
    ) {
      return null;
    }

    return hostname;
  } catch {
    return null;
  }
}

export function normalizeVisitorHash(
  value
) {
  if (
    typeof value !== 'string'
  ) {
    return null;
  }

  const normalized =
    value.trim();

  if (
    normalized.length === 0 ||
    normalized.length >
      MAX_VISITOR_HASH_LENGTH
  ) {
    return null;
  }

  /*
   * Accept only a hexadecimal SHA-256 style
   * value generated by our server/client flow.
   */
  if (
    !/^[a-f0-9]{64}$/i.test(
      normalized
    )
  ) {
    return null;
  }

  return normalized.toLowerCase();
}

export function validateAnalyticsInput(
  input
) {
  return {
    deviceType:
      normalizeDeviceType(
        input?.device_type
      ),

    referrerDomain:
      normalizeReferrer(
        input?.referrer
      ),

    visitorHash:
      normalizeVisitorHash(
        input?.visitor_hash
      ),
  };
}